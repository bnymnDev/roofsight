"""``roofsight leaderboard``: regenerate docs/leaderboard.md and paper/results.tex from runs/.

A run is listed only if it has ``run.json`` and ``metrics.json``. Both files are written by
``roofsight eval``; nothing here is typed by hand.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from roofsight.run import RUN_FILE, RunRecord, read_run

METRICS_FILE = "metrics.json"
LATENCY_FILE = "latency.json"

COLUMNS = (
    "model",
    "params",
    "mask AP",
    "small-obstacle recall",
    "boundary F",
    "CPU ms",
    "iPhone ms",
    "dataset",
    "run id",
)


@dataclass(slots=True)
class Row:
    model: str
    params_m: float | None
    mask_ap: float
    small_obstacle_recall: float
    boundary_f: float
    cpu_ms: float | None
    iphone_ms: float | None
    dataset_version: str
    run_id: str

    def _fmt(self, v: float | None, digits: int = 1) -> str:
        return "–" if v is None else f"{v:.{digits}f}"

    def markdown(self) -> str:
        return (
            "| "
            + " | ".join(
                [
                    self.model,
                    self._fmt(self.params_m) + ("M" if self.params_m is not None else ""),
                    f"{100 * self.mask_ap:.1f}",
                    f"{100 * self.small_obstacle_recall:.1f}",
                    f"{100 * self.boundary_f:.1f}",
                    self._fmt(self.cpu_ms),
                    self._fmt(self.iphone_ms),
                    self.dataset_version,
                    f"`{self.run_id}`",
                ]
            )
            + " |"
        )

    def latex(self) -> str:
        cells = [
            self.model.replace("_", r"\_"),
            self._fmt(self.params_m) + ("M" if self.params_m is not None else ""),
            f"{100 * self.mask_ap:.1f}",
            f"{100 * self.small_obstacle_recall:.1f}",
            f"{100 * self.boundary_f:.1f}",
            self._fmt(self.cpu_ms),
            self._fmt(self.iphone_ms),
            self.dataset_version,
        ]
        return " & ".join(cells) + r" \\"


def _latency_ms(run_dir: Path, backend: str) -> float | None:
    path = run_dir / LATENCY_FILE
    if not path.exists():
        return None
    for rec in json.loads(path.read_text(encoding="utf-8")):
        if rec.get("backend") == backend:
            return float(rec["median_ms"])
    return None


def collect(runs_root: Path) -> list[Row]:
    rows: list[Row] = []
    if not runs_root.exists():
        return rows
    for run_dir in sorted(runs_root.iterdir()):
        if not (run_dir / RUN_FILE).exists() or not (run_dir / METRICS_FILE).exists():
            continue
        run: RunRecord = read_run(run_dir)
        if run.kind != "eval":
            continue
        m = json.loads((run_dir / METRICS_FILE).read_text(encoding="utf-8"))
        params = run.config.get("params_m")
        rows.append(
            Row(
                model=str(run.config.get("model", "unknown")),
                params_m=float(params) if params is not None else None,
                mask_ap=float(m["mask_ap"]),
                small_obstacle_recall=float(m["small_obstacle_recall"]),
                boundary_f=float(m["boundary_f"]),
                cpu_ms=_latency_ms(run_dir, "onnxruntime-cpu"),
                iphone_ms=_latency_ms(run_dir, "coreml-iphone"),
                dataset_version=run.dataset_version,
                run_id=run.run_id,
            )
        )
    rows.sort(key=lambda r: r.mask_ap, reverse=True)
    return rows


def render_markdown(rows: list[Row]) -> str:
    head = "| " + " | ".join(COLUMNS) + " |\n|" + "---|" * len(COLUMNS) + "\n"
    body = "\n".join(r.markdown() for r in rows) if rows else "| _no runs yet_ |" + " |" * 8
    return (
        "# Leaderboard\n\n"
        "<!-- generated by `roofsight leaderboard`; do not edit by hand -->\n\n"
        "Mask AP, small-obstacle recall (@IoU 0.5, < 32² px) and boundary F in %. "
        "Latency is the median of 50 runs at 640 px. Every row has a `run.json`.\n\n"
        + head
        + body
        + "\n"
    )


def render_latex(rows: list[Row]) -> str:
    lines = [
        "% generated by `roofsight leaderboard`; do not edit by hand",
        r"\begin{tabular}{lrrrrrrl}",
        r"\toprule",
        r"Model & Params & Mask AP & Small-obst. R & Boundary F & CPU ms & iPhone ms & Dataset \\",
        r"\midrule",
        *[r.latex() for r in rows],
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def regenerate(runs_root: Path, md_out: Path, tex_out: Path) -> list[Row]:
    rows = collect(runs_root)
    md_out.parent.mkdir(parents=True, exist_ok=True)
    tex_out.parent.mkdir(parents=True, exist_ok=True)
    md_out.write_text(render_markdown(rows), encoding="utf-8")
    tex_out.write_text(render_latex(rows), encoding="utf-8")
    return rows
